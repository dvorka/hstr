EOF

# decode <encoded value> - to variable DECODED (keeps trailing newlines)
decode() {
    printf -v DECODED -- "$1X"
    DECODED=${DECODED%X}
}

# assign_code <variable> <encoded value> - prints shell code which assigns the value
assign_code() {
    case "$2" in
        UNSET) printf 'unset %s\n' "$1" ;;
        EMPTY) printf '%s=\n' "$1" ;;
        *) printf '%s=$(printf -- "%s"X); %s=${%s%%X}\n' "$1" "$2" "$1" "$1" ;;
    esac
}

# semantics <guard> <encoded value> - prints HISTSIZE|HISTFILESIZE|exit code
semantics() {
    local out rc
    out=$(env -i PATH="$PATH" LC_ALL="$LOCALE" bash -c "
        set -u
        $(assign_code HISTSIZE "$2")
        $(assign_code HISTFILESIZE "$2")
        source '$1' || exit 99
        printf '%s|%s' \"\${HISTSIZE-<unset>}\" \"\${HISTFILESIZE-<unset>}\"
    " 2>"$WORK/err")
    rc=$?
    [ -s "$WORK/err" ] && rc="$rc+stderr"
    printf '%s|%s' "$out" "$rc" | tr '\n' '~'
}

# file_lines <guard> <encoded value> - history file lines, HISTFILESIZE assigned in rc
file_lines() {
    make_history_file "$WORK/home/history"
    {
        printf 'HISTFILE=%s\n' "$WORK/home/history"
        printf 'shopt -s histappend\n'
        printf 'HISTSIZE=100000\n'
        assign_code HISTFILESIZE "$2"
        printf 'source %s\n' "$1"
    } > "$WORK/rc"
    run_interactive "$WORK/rc" ":"
    wc -l < "$WORK/home/history" | tr -d ' '
}

# env_lines <guard> <encoded value> - history file lines, HISTFILESIZE inherited
env_lines() {
    make_history_file "$WORK/home/history"
    {
        printf 'HISTFILE=%s\n' "$WORK/home/history"
        printf 'shopt -s histappend\n'
        printf 'source %s\n' "$1"
    } > "$WORK/rc"
    case "$2" in
        UNSET) run_interactive "$WORK/rc" ":" HISTSIZE=100000 ;;
        EMPTY) run_interactive "$WORK/rc" ":" HISTSIZE=100000 HISTFILESIZE= ;;
        *) decode "$2"; run_interactive "$WORK/rc" ":" HISTSIZE=100000 "HISTFILESIZE=$DECODED" ;;
    esac
    wc -l < "$WORK/home/history" | tr -d ' '
}

# memory_lines <guard> <encoded value> - entries loaded to in-memory history
memory_lines() {
    make_history_file "$WORK/home/history"
    {
        printf 'HISTFILE=%s\n' "$WORK/home/history"
        printf 'HISTFILESIZE=-1\n'
        assign_code HISTSIZE "$2"
        printf 'source %s\n' "$1"
    } > "$WORK/rc"
    # HISTFILE is unset before exit so that the file is not rewritten
    run_interactive "$WORK/rc" "history | wc -l > '$WORK/count'; unset HISTFILE"
    tr -d ' ' < "$WORK/count"
}

# label <encoded value> - printable, shortened value
label() {
    printf '%s' "$1" | cut -c1-22
}

printf '\n%-22s | %-12s | %-30s | %s\n' "value" "test" "bash w/o guard" "HSTR guard"
printf -- '-%.0s' $(seq 1 100)
printf '\n'

while IFS= read -r value; do
    name=$(label "$value")

    # bash accepts whitespace and sign around a number - the guard keeps such values
    note=
    case "$value" in
        '\x20'*|*'\x20'|'+'*|'-0'|'\n'*|*'\n') note="not raised by the guard, never shrunk" ;;
    esac
    # bash < 4.3 has no unlimited (negative) HISTSIZE and overflows huge values to 0
    memory_note=$note
    if [ "${BASH_VERSINFO[0]}" -lt 4 ] || { [ "${BASH_VERSINFO[0]}" -eq 4 ] && [ "${BASH_VERSINFO[1]}" -lt 3 ]; }; then
        case "$value" in
            -*|9223372036854775807) memory_note="bash < 4.3 keeps no history for this HISTSIZE" ;;
        esac
    fi

    s_base=$(semantics "$WORK/baseline.sh" "$value")
    s_hstr=$(semantics "$GUARD" "$value")
    printf '%-22s | %-12s | %-30s | %s\n' "$name" "S set -u" "$s_base" "$s_hstr"
    case "$s_hstr" in
        *"|0") check 0 "" ;;
        *) check 1 "$name: guard fails with set -u ($s_hstr)" ;;
    esac

    f_base=$(file_lines "$WORK/baseline.sh" "$value")
    f_hstr=$(file_lines "$GUARD" "$value")
    printf '%-22s | %-12s | %-30s | %s\n' "" "F file lines" "$f_base" "$f_hstr"
    [ "$f_hstr" -ge "$f_base" ]
    check $? "$name: guard truncated history file ($f_hstr < $f_base)"

    e_base=$(env_lines "$WORK/baseline.sh" "$value")
    e_hstr=$(env_lines "$GUARD" "$value")
    printf '%-22s | %-12s | %-30s | %s\n' "" "E env lines" "$e_base" "$e_hstr"
    [ "$e_hstr" -ge "$e_base" ]
    check $? "$name: guard truncated history file ($e_hstr < $e_base)"
    if [ "$e_base" -lt 10000 ]; then
        [ "$e_hstr" -ge 10000 ]
        check $? "$name: guard did not raise history file ($e_hstr)" "$note"
    fi

    m_base=$(memory_lines "$WORK/baseline.sh" "$value")
    m_hstr=$(memory_lines "$GUARD" "$value")
    printf '%-22s | %-12s | %-30s | %s\n' "" "M mem lines" "$m_base" "$m_hstr"
    [ "$m_hstr" -ge "$m_base" ]
    check $? "$name: guard shrank in-memory history ($m_hstr < $m_base)"
    if [ "$m_base" -lt 10000 ]; then
        [ "$m_hstr" -ge 10000 ]
        check $? "$name: guard did not raise in-memory history ($m_hstr)" "$memory_note"
    fi
done < "$VALUES"

printf '\nbash %s, locale %s: %d checks, %d failures, %d notes\n' \
    "$BASH_VERSION" "$LOCALE" "$CHECKS" "$FAILS" "$NOTES"
if [ "$FAILS" -ne 0 ]; then
    printf 'FAILED\n'
    exit 1
fi
printf 'DONE\n'

# eof
