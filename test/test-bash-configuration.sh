# Regression test of the bash configuration printed by hstr --show-bash-configuration
#
# usage:
#   test-bash-configuration.sh [<bash configuration file>]
#
# If no file is given, then the configuration is generated by ../src/hstr - without
# controlling terminal (setsid) to check that the output is clean in scripts too. The file
# argument allows to run the test with other bash versions e.g. in a container:
#
#   ../src/hstr --show-bash-configuration > /tmp/hstr-bash.sh
#   docker run --rm -v /tmp:/t -v $(pwd):/test:ro bash:3.2 \
#       bash /test/test-bash-configuration.sh /t/hstr-bash.sh
#
# Environment:
#   HSTR_TEST_LOCALE ... locale to run bash with (default C) e.g. cs_CZ.UTF-8
#
# Tests:
#   C  configuration: clean output (no diagnostics), no errors when sourced by an
#      interactive bash with set -u (nounset)
#   history size guard - compared to bash w/o the guard (baseline), 20000 lines history:
#   S  semantics: values of HISTSIZE/HISTFILESIZE after the guard with set -u
#   F  history file lines after a session, HISTFILESIZE assigned in rc before the guard
#      (bash truncates the file at the assignment itself - guard can only avoid worse)
#   E  history file lines after a session, HISTFILESIZE inherited from the environment
#   M  in-memory history entries, HISTSIZE assigned in rc before the guard
#
# Properties (any violation is a FAIL):
#   P1 the guard never loses history compared to the baseline (F, E, M)
#   P2 the guard raises history to 10000+ entries if the baseline keeps fewer (E, M) -
#      except values bash parses as numbers but the guard intentionally keeps (NOTE)
#   P3 no shell error, also with set -u (C, S)
#
# The test runs bash with isolated HOME and HISTFILE - user's history is never touched.

set -o nounset

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
WORK=$(mktemp -d "${TMPDIR:-/tmp}/hstr-test-bash-configuration.XXXXXX") || exit 1
trap 'rm -rf "$WORK"' EXIT
LOCALE=${HSTR_TEST_LOCALE:-C}
LINES_IN_FILE=20000

FAILS=0
NOTES=0
CHECKS=0

# check <exit code of condition> <message> [<note>]
check() {
    CHECKS=$((CHECKS+1))
    if [ "$1" != 0 ]; then
        if [ -n "${3-}" ]; then
            NOTES=$((NOTES+1))
            printf '    NOTE: %s - %s\n' "$2" "$3"
        else
            FAILS=$((FAILS+1))
            printf '    FAIL: %s\n' "$2"
        fi
    fi
}

#
# configuration
#

CONFIGURATION="$WORK/configuration.sh"
if [ $# -ge 1 ]; then
    cp "$1" "$CONFIGURATION" || exit 1
else
    HSTR="$SCRIPT_DIR/../src/hstr"
    if [ ! -x "$HSTR" ]; then
        printf 'ERROR: %s not found - build HSTR first\n' "$HSTR"
        exit 1
    fi
    if ! command -v setsid >/dev/null 2>&1; then
        printf 'ERROR: setsid not found\n'
        exit 1
    fi
    # setsid detaches HSTR from the controlling terminal like in scripts
    setsid "$HSTR" --show-bash-configuration > "$CONFIGURATION" 2>/dev/null < /dev/null
fi

GUARD="$WORK/guard.sh"
grep 'SIZE=10000; fi$' "$CONFIGURATION" > "$GUARD"
: > "$WORK/baseline.sh"

printf 'bash %s, locale %s\n\n' "$BASH_VERSION" "$LOCALE"
printf 'C configuration\n'

[ "$(wc -l < "$GUARD" | tr -d ' ')" = 2 ]
check $? "history size guard (2 lines) not found in the configuration"

! grep -q 'Error' "$CONFIGURATION"
check $? "configuration contains diagnostics: $(grep 'Error' "$CONFIGURATION" | head -1)"

bash -n "$CONFIGURATION"
check $? "configuration has syntax errors"

# interactive bash w/ isolated HOME and HISTFILE, history file w/ LINES_IN_FILE lines
make_history_file() {
    local i=1
    while [ $i -le $LINES_IN_FILE ]; do
        printf 'echo %d\n' $i
        i=$((i+1))
    done > "$1"
}

# run_interactive <rc file> <commands> [<env assignments>...]
run_interactive() {
    local rc=$1 commands=$2
    shift 2
    env -i PATH="$PATH" LC_ALL="$LOCALE" HOME="$WORK/home" TERM=dumb "$@" \
        bash --rcfile "$rc" -i >"$WORK/out" 2>"$WORK/err" <<EOF
$commands
exit
EOF
}

mkdir -p "$WORK/home"
make_history_file "$WORK/home/history"
{
    printf 'HISTFILE=%s\n' "$WORK/home/history"
    printf 'set -u\n'
    printf 'source %s\n' "$CONFIGURATION"
    printf 'set +u\n'
} > "$WORK/rc"
run_interactive "$WORK/rc" 'echo "PROMPT_COMMAND=$PROMPT_COMMAND"'
! grep -E 'unbound variable|command not found|syntax error' "$WORK/err" > "$WORK/errors"
check $? "configuration fails with set -u: $(head -1 "$WORK/errors")"
grep -q '^PROMPT_COMMAND=history -a; history -n; $' "$WORK/out"
check $? "PROMPT_COMMAND not set with set -u: $(grep PROMPT_COMMAND "$WORK/out")"

#
# history size guard
#

# values are printf encoded (one per line) so that whitespace and newlines can be tested
VALUES="$WORK/values.txt"
cat > "$VALUES" <<'EOF'
UNSET
EMPTY
0
1
500
9999
09999
0000000000000000000000500
00000
10000
010000
020000
99999
100000000
9223372036854775807
9223372036854775808
